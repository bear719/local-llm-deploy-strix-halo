"""把译文里的繁体字逐字替换为简体（仅覆盖常见字），用于纠正模型偶发繁体。"""
import json, sys, pathlib

M = {
 "們":"们","個":"个","這":"这","說":"说","為":"为","對":"对","開":"开","關":"关","編":"编","輯":"辑",
 "訊":"讯","應":"应","與":"与","來":"来","時":"时","間":"间","樣":"样","麼":"么","點":"点","選":"选",
 "單":"单","頁":"页","檔":"档","數":"数","據":"据","網":"网","設":"设","確":"确","認":"认","載":"载",
 "儲":"储","檢":"检","視":"视","刪":"删","處":"处","裡":"里","從":"从","會":"会","後":"后","發":"发",
 "現":"现","實":"实","體":"体","變":"变","無":"无","嗎":"吗","頻":"频","進":"进","顯":"显","統":"统",
 "語":"语","資":"资","錯":"错","誤":"误","讀":"读","寫":"写","給":"给","還":"还","過":"过","長":"长",
 "內":"内","執":"执","行":"行","稱":"称","啟":"启","動":"动","產":"产","標":"标","準":"准","簽":"签",
 "號":"号","終":"终","點":"点","顯":"显","傳":"传","輸":"输","連":"连","線":"线","終":"终","許":"许",
 "詳":"详","課":"课","題":"题","屬":"属","處":"处","離":"离","雜":"杂","嚴":"严","環":"环","節":"节",
 "劃":"划","圖":"图","滅":"灭","響":"响","驗":"验","證":"证","權":"权","組":"组","織":"织","寬":"宽",
 "環":"环","擴":"扩","撥":"拨","擊":"击","為":"为","覽":"览","覽":"览","戶":"户","壇":"坛","彈":"弹",
}

def fix(s: str) -> str:
    return "".join(M.get(ch, ch) for ch in s)

def main():
    hits = 0
    for p in ["dict.json", "dict_lits.json"]:
        f = pathlib.Path(p)
        d = json.load(open(f, encoding="utf-8"))
        n = 0
        for k, v in list(d.items()):
            if isinstance(v, str):
                nv = fix(v)
                if nv != v:
                    d[k] = nv
                    n += 1
        json.dump(d, open(f, "w", encoding="utf-8"), ensure_ascii=False, indent=1)
        print(p, "修正", n)
        hits += n
    print("合计", hits)

if __name__ == "__main__":
    main()
